// Package runtimegen combines locked registry and inventory data.
package runtimegen

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"
	"sort"

	"github.com/bedrock-mc/protocolgen/data/source"
)

// GeneratedMarker identifies files owned by the runtime catalog generator.
const GeneratedMarker = "// Code generated by data/cmd/runtimegen; DO NOT EDIT."

// RegistryEntry holds the normalized identity of one vanilla item.
type RegistryEntry struct {
	RuntimeID      int32 `json:"runtime_id"`
	ComponentBased bool  `json:"component_based"`
	Version        int32 `json:"version"`
}

// Properties contains the inventory fields needed from a vanilla item extract.
type Properties struct {
	MaxStackSize int      `json:"maxStackSize"`
	Tags         []string `json:"tags"`
}

// Corrections fills known omissions in the locked extraction. A correction
// becomes an error when its source gains the field or its item leaves the registry.
type Corrections struct {
	StackSizes  map[string]int        `json:"stack_sizes"`
	StackLimits map[string]StackLimit `json:"stack_limits"`
	Offhand     []string              `json:"offhand"`
	Helmets     []string              `json:"helmets"`
	Evidence    map[string]string     `json:"evidence"`
}

// StackLimit replaces a raw item field with its measured effective stack limit.
// ExpectedSourceCount makes an upstream change fail instead of retaining a stale override.
type StackLimit struct {
	ExpectedSourceCount int `json:"expected_source_count"`
	EffectiveCount      int `json:"effective_count"`
}

// FromSources authenticates all inputs and generates the complete runtime catalog.
func FromSources(ctx context.Context, inputs *source.Sources, cache string) ([]byte, error) {
	if err := inputs.ValidateNative(ctx, cache); err != nil {
		return nil, err
	}
	registryJSON, err := inputs.Read(ctx, "item_registry", cache)
	if err != nil {
		return nil, err
	}
	registry, err := DecodeRegistry(registryJSON)
	if err != nil {
		return nil, fmt.Errorf("decode item_registry: %w", err)
	}
	propertiesJSON, err := inputs.Read(ctx, "native_item_properties", cache)
	if err != nil {
		return nil, err
	}
	properties, err := DecodeNativeProperties(propertiesJSON, registry)
	if err != nil {
		return nil, fmt.Errorf("decode native_item_properties: %w", err)
	}
	nativeTags, err := inputs.Read(ctx, "native_item_tags", cache)
	if err != nil {
		return nil, err
	}
	if err := validateNativeTags(properties, nativeTags); err != nil {
		return nil, err
	}
	var tags map[string][]string
	var corrections Corrections
	for _, input := range []struct {
		name string
		out  any
	}{{"item_tags", &tags}, {"item_corrections", &corrections}} {
		data, err := inputs.Read(ctx, input.name, cache)
		if err != nil {
			return nil, err
		}
		if err := json.Unmarshal(data, input.out); err != nil {
			return nil, fmt.Errorf("decode %s: %w", input.name, err)
		}
	}
	return Generate(registry, properties, tags, corrections)
}

// DecodeRegistry reads Cloudburst's registry without silently defaulting missing fields.
func DecodeRegistry(data []byte) (map[string]RegistryEntry, error) {
	var rows []struct {
		Name           string `json:"name"`
		ID             *int32 `json:"id"`
		ComponentBased *bool  `json:"componentBased"`
		Version        *int32 `json:"version"`
	}
	if err := json.Unmarshal(data, &rows); err != nil {
		return nil, err
	}
	registry := make(map[string]RegistryEntry, len(rows))
	for _, row := range rows {
		if row.Name == "" || row.ID == nil || row.ComponentBased == nil || row.Version == nil {
			return nil, fmt.Errorf("item %q has incomplete registry fields", row.Name)
		}
		if _, exists := registry[row.Name]; exists {
			return nil, fmt.Errorf("duplicate registry item %s", row.Name)
		}
		registry[row.Name] = RegistryEntry{*row.ID, *row.ComponentBased, *row.Version}
	}
	return registry, nil
}

// DecodeNativeProperties reads stack sizes and native tags when the dump
// covers the registry exactly. Missing tags mean no tags; inventory slot
// capabilities are supplied separately rather than inferred from these tags.
func DecodeNativeProperties(data []byte, registry map[string]RegistryEntry) (map[string]Properties, error) {
	var rows map[string]*struct {
		ID           *int32   `json:"id"`
		MaxStackSize *int     `json:"maxStackSize"`
		Tags         []string `json:"tags"`
	}
	if err := json.Unmarshal(data, &rows); err != nil {
		return nil, err
	}
	if len(registry) == 0 {
		return nil, fmt.Errorf("item registry is empty")
	}
	properties := make(map[string]Properties, len(rows))
	for name, row := range rows {
		entry, ok := registry[name]
		if !ok {
			return nil, fmt.Errorf("native properties reference unknown item %s", name)
		}
		if row == nil || row.ID == nil || row.MaxStackSize == nil {
			return nil, fmt.Errorf("native item %s has incomplete properties", name)
		}
		if *row.ID != entry.RuntimeID {
			return nil, fmt.Errorf("native item %s has runtime ID %d, registry has %d", name, *row.ID, entry.RuntimeID)
		}
		if size := *row.MaxStackSize; size < 1 || size > 64 {
			return nil, fmt.Errorf("native item %s has invalid stack size %d", name, size)
		}
		properties[name] = Properties{MaxStackSize: *row.MaxStackSize, Tags: row.Tags}
	}
	for name := range registry {
		if _, ok := properties[name]; !ok {
			return nil, fmt.Errorf("native properties are missing item %s", name)
		}
	}
	return properties, nil
}

// Generate emits one deterministic inventory catalog without importing consumers.
func Generate(registry map[string]RegistryEntry, properties map[string]Properties, tags map[string][]string, corrections Corrections) ([]byte, error) {
	if len(registry) == 0 {
		return nil, fmt.Errorf("item registry is empty")
	}
	for _, required := range []string{"minecraft:allow_offhand", "minecraft:head"} {
		if len(tags[required]) == 0 {
			return nil, fmt.Errorf("required item tag %q is missing or empty", required)
		}
	}
	if len(corrections.Evidence) == 0 && (len(corrections.StackSizes)+len(corrections.StackLimits)+len(corrections.Offhand)+len(corrections.Helmets) > 0) {
		return nil, fmt.Errorf("item corrections need evidence")
	}
	for name, size := range corrections.StackSizes {
		if _, ok := registry[name]; !ok {
			return nil, fmt.Errorf("stack correction references unknown item %s", name)
		}
		if properties[name].MaxStackSize > 0 {
			return nil, fmt.Errorf("stack correction for %s is stale: source now supplies a value", name)
		}
		if size < 1 || size > 64 {
			return nil, fmt.Errorf("stack correction for %s has invalid count %d", name, size)
		}
	}
	for name, limit := range corrections.StackLimits {
		if _, ok := registry[name]; !ok {
			return nil, fmt.Errorf("stack limit correction references unknown item %s", name)
		}
		if limit.ExpectedSourceCount < 1 || limit.ExpectedSourceCount > 64 || limit.EffectiveCount < 1 || limit.EffectiveCount > 64 {
			return nil, fmt.Errorf("stack limit correction for %s has invalid counts", name)
		}
		if properties[name].MaxStackSize != limit.ExpectedSourceCount || limit.ExpectedSourceCount == limit.EffectiveCount {
			return nil, fmt.Errorf("stack limit correction for %s is stale: source count is %d", name, properties[name].MaxStackSize)
		}
	}
	offhand, err := correctedTag(registry, tags["minecraft:allow_offhand"], corrections.Offhand)
	if err != nil {
		return nil, err
	}
	helmet, err := correctedTag(registry, tags["minecraft:head"], corrections.Helmets)
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(registry))
	for name := range registry {
		names = append(names, name)
	}
	sort.Strings(names)
	var output bytes.Buffer
	fmt.Fprintln(&output, GeneratedMarker+"\n\npackage item\n\nvar runtimeItems = []Runtime{")
	ids := make(map[int32]string)
	for _, name := range names {
		entry, props := registry[name], properties[name]
		if previous, ok := ids[entry.RuntimeID]; ok {
			return nil, fmt.Errorf("items %s and %s share runtime ID %d", previous, name, entry.RuntimeID)
		}
		ids[entry.RuntimeID] = name
		count := props.MaxStackSize
		if count <= 0 {
			count = corrections.StackSizes[name]
		}
		if limit, ok := corrections.StackLimits[name]; ok {
			count = limit.EffectiveCount
		}
		if count < 1 || count > 64 {
			return nil, fmt.Errorf("item %s has missing or invalid stack size %d", name, count)
		}
		body := slices.Contains(props.Tags, "minecraft:horse_armor") || slices.Contains(props.Tags, "minecraft:nautilus_armor") || slices.Contains(props.Tags, "minecraft:harness")
		fmt.Fprintf(&output, "{Name:%q, RuntimeID:%d, ComponentBased:%t, Version:%d, MaxCount:%d, BodyWearable:%t, AllowOffHand:%t, ArmourSlot:0, ArmourWearable:%t},\n", name, entry.RuntimeID, entry.ComponentBased, entry.Version, count, body, offhand[name], helmet[name])
	}
	fmt.Fprintln(&output, "}\n\nvar runtimeTags = map[string][]string{")
	for _, name := range names {
		if len(properties[name].Tags) > 0 {
			fmt.Fprintf(&output, "%q:%#v,\n", name, properties[name].Tags)
		}
	}
	fmt.Fprintln(&output, "}")
	return format.Source(output.Bytes())
}

// correctedTag applies missing-membership corrections and rejects stale entries.
func correctedTag(registry map[string]RegistryEntry, members, corrections []string) (map[string]bool, error) {
	result := make(map[string]bool, len(members)+len(corrections))
	for _, name := range members {
		result[name] = true
	}
	for _, name := range corrections {
		if _, ok := registry[name]; !ok {
			return nil, fmt.Errorf("tag correction references unknown item %s", name)
		}
		if result[name] {
			return nil, fmt.Errorf("tag correction for %s is stale or duplicated", name)
		}
		result[name] = true
	}
	return result, nil
}

// validateNativeTags requires the per-item and per-tag dumps to describe the same memberships.
func validateNativeTags(properties map[string]Properties, data []byte) error {
	var declared map[string][]string
	if err := json.Unmarshal(data, &declared); err != nil {
		return fmt.Errorf("decode native item tags: %w", err)
	}
	actual := make(map[string][]string)
	for name, item := range properties {
		seen := make(map[string]bool)
		for _, tag := range item.Tags {
			if tag == "" || seen[tag] {
				return fmt.Errorf("item %s has empty or duplicate tag %q", name, tag)
			}
			seen[tag] = true
			actual[tag] = append(actual[tag], name)
		}
	}
	if len(actual) != len(declared) {
		return fmt.Errorf("native item tag domains differ: %d versus %d", len(actual), len(declared))
	}
	for tag, members := range declared {
		expected, ok := actual[tag]
		if !ok || len(members) == 0 {
			return fmt.Errorf("native item tag %s has no matching members", tag)
		}
		members = slices.Clone(members)
		sort.Strings(members)
		sort.Strings(expected)
		if !slices.Equal(members, expected) {
			return fmt.Errorf("native item tag %s membership differs from item properties", tag)
		}
	}
	return nil
}
