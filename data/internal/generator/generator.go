type generatedState struct {
	Hash       uint32
	Block      uint16
	Properties uint16
}

// generateBlocks normalizes state properties and compacts shared block shapes.
func generateBlocks(path string, omissions []LiquidClipOmission, native *nativeblock.Catalog) (map[string][]byte, int, error) {
	var raw []rawBlockState
	if err := readJSON(path, &raw, false); err != nil {
		return nil, 0, err
	}
	if len(raw) > math.MaxUint16 {
		return nil, 0, fmt.Errorf("state count %d exceeds uint16 lookup capacity", len(raw))
	}
	if native != nil {
		if err := applyNativeBlocks(raw, *native); err != nil {
			return nil, 0, err
		}
	}
	if err := prepareBlockShapes(raw, omissions); err != nil {
		return nil, 0, err
	}

	blocks := make([]generatedBlock, 0, 2048)
	blockIndexes := make(map[generatedBlock]uint16)
	properties := make([]generatedProperties, 0, 4096)
	propertyIndexes := make(map[generatedProperties]uint16)
	shapes := make([][]generatedBox, 1)
	shapeIndexes := make(map[string]uint16)
	states := make([]generatedState, 0, len(raw))
	seenHashes := make(map[uint32]struct{}, len(raw))

	internShape := func(message json.RawMessage) (uint16, error) {
		boxes, present, err := decodeShape(message)
		if err != nil {
			return 0, err
		}
		if !present {
			return 0, nil
		}
		key := shapeKey(boxes)
		if index, ok := shapeIndexes[key]; ok {
			return index, nil
		}
		if len(shapes) == math.MaxUint16 {
			return 0, errors.New("shape count exceeds uint16 capacity")
		}
		index := uint16(len(shapes))
		shapeIndexes[key] = index
		shapes = append(shapes, boxes)
		return index, nil
	}

	for sourceIndex, value := range raw {
		if value.Name == "" {
			return nil, 0, fmt.Errorf("state %d has no name", sourceIndex)
		}
		if _, found := seenHashes[value.Hash]; found {
			return nil, 0, fmt.Errorf("duplicate block state hash %d", value.Hash)
		}
		seenHashes[value.Hash] = struct{}{}

		blockValue := generatedBlock{Name: value.Name, TranslationKey: value.TranslationKey}
		blockIndex, ok := blockIndexes[blockValue]
		if !ok {
			if len(blocks) == math.MaxUint16 {
				return nil, 0, errors.New("block count exceeds uint16 capacity")
			}
			blockIndex = uint16(len(blocks))
			blockIndexes[blockValue] = blockIndex
			blocks = append(blocks, blockValue)
		}

		collision, err := internShape(value.CollisionShape)
		if err != nil {
			return nil, 0, fmt.Errorf("%s collision shape: %w", value.Name, err)
		}
		outline, err := internShape(value.OutlineShape)
		if err != nil {
			return nil, 0, fmt.Errorf("%s outline shape: %w", value.Name, err)
		}
		visual, err := internShape(value.VisualShape)
		if err != nil {
			return nil, 0, fmt.Errorf("%s visual shape: %w", value.Name, err)
		}
		ui, err := internShape(value.UIShape)
		if err != nil {
			return nil, 0, fmt.Errorf("%s UI shape: %w", value.Name, err)
		}
		liquidClip, err := internShape(value.LiquidClipShape)
		if err != nil {
			return nil, 0, fmt.Errorf("%s liquid clip shape: %w", value.Name, err)
		}
		mapColor, err := parseRGBA(value.MapColor)
		if err != nil {
			return nil, 0, fmt.Errorf("%s map color: %w", value.Name, err)
		}
		propertyValue := generatedProperties{
			Hardness:                    value.Hardness,
			ExplosionResistance:         value.ExplosionResistance,
			Friction:                    value.Friction,
			Thickness:                   value.Thickness,
			Translucency:                value.Translucency,
			MapColor:                    mapColor,
			TintMethod:                  value.TintMethod,
			LiquidReactionOnTouch:       value.LiquidReactionOnTouch,
			LightEmission:               value.LightEmission,
			LightDampening:              value.LightDampening,
			BurnOdds:                    value.BurnOdds,
			FlameOdds:                   value.FlameOdds,
			CollisionShape:              collision,
			OutlineShape:                outline,
			VisualShape:                 visual,
			UIShape:                     ui,
			LiquidClipShape:             liquidClip,
			Solid:                       value.Solid,
			RequiresCorrectToolForDrops: value.RequiresCorrectToolForDrops,
			CanContainLiquidSource:      value.CanContainLiquidSource,
		}
		propertyIndex, ok := propertyIndexes[propertyValue]
		if !ok {
			if len(properties) == math.MaxUint16 {
				return nil, 0, errors.New("property count exceeds uint16 capacity")
			}
			propertyIndex = uint16(len(properties))
			propertyIndexes[propertyValue] = propertyIndex
			properties = append(properties, propertyValue)
		}
		states = append(states, generatedState{
			Hash: value.Hash, Block: blockIndex, Properties: propertyIndex,
		})
	}

	hashIndex := make([]uint16, len(states))
	for index := range states {
		hashIndex[index] = uint16(index)
	}
	sort.Slice(hashIndex, func(i, j int) bool {
		return states[hashIndex[i]].Hash < states[hashIndex[j]].Hash
	})

	blockNames := make([]string, len(blocks))
	for index, value := range blocks {
		blockNames[index] = value.Name
	}
	identifiers, err := exportedIdentifiers(blockNames)
	if err != nil {
		return nil, 0, err
	}
	fileNames, err := generatedFileNames(blockNames)
	if err != nil {
		return nil, 0, err
	}
	stateIndexesByBlock := make([][]int, len(blocks))
	for stateIndex, state := range states {
		stateIndexesByBlock[state.Block] = append(stateIndexesByBlock[state.Block], stateIndex)
	}

	files := make(map[string][]byte, len(blocks)+1)
	for blockIndex, value := range blocks {
		identifier := identifiers[value.Name]
		stateVariable := unexportedIdentifier(identifier) + "States"
		var output bytes.Buffer
		fmt.Fprintf(&output, `// %s is the generated definition for %s.
var %s = Block{
	Name: %q,
	TranslationKey: %q,
}

var %s = [...]State{
`, identifier, value.Name, identifier, value.Name, value.TranslationKey, stateVariable)
		for _, stateIndex := range stateIndexesByBlock[blockIndex] {
			state := states[stateIndex]
			fmt.Fprintf(&output, "{Hash: %d, Block: %d, Properties: %d},\n",
				state.Hash, state.Block, state.Properties)
		}
		output.WriteString("}\n")
		fileName := "block/" + fileNames[value.Name]
		formatted, err := formattedGo(fileName, generatedSource("block", output.String()))
		if err != nil {
			return nil, 0, err
		}
		files[fileName] = formatted
	}

	var output bytes.Buffer
	output.WriteString("var blocks = [...]Block{\n")
	for _, value := range blocks {
		fmt.Fprintf(&output, "%s,\n", identifiers[value.Name])
	}
	output.WriteString("}\n\nvar shapes = [...][]Box{\n")
	for _, shape := range shapes {
		if shape == nil {
			output.WriteString("nil,\n")
			continue
		}
		output.WriteString("{")
		for _, box := range shape {
			fmt.Fprintf(&output, "{%s, %s, %s, %s, %s, %s},",
				goFloat(box[0]), goFloat(box[1]), goFloat(box[2]),
				goFloat(box[3]), goFloat(box[4]), goFloat(box[5]))
		}
		output.WriteString("},\n")
	}
	output.WriteString("}\n\nvar properties = [...]Properties{\n")
	for _, value := range properties {
		fmt.Fprintf(&output, `{Hardness:%s, ExplosionResistance:%s, Friction:%s, Thickness:%s, Translucency:%s, MapColor:0x%08x, TintMethod:%q, LiquidReactionOnTouch:%q, LightEmission:%d, LightDampening:%d, BurnOdds:%d, FlameOdds:%d, CollisionShape:%d, OutlineShape:%d, VisualShape:%d, UIShape:%d, LiquidClipShape:%d, Solid:%t, RequiresCorrectToolForDrops:%t, CanContainLiquidSource:%t},
`,
			goFloat(value.Hardness), goFloat(value.ExplosionResistance), goFloat(value.Friction),
			goFloat(value.Thickness), goFloat(value.Translucency), value.MapColor, value.TintMethod,
			value.LiquidReactionOnTouch, value.LightEmission, value.LightDampening, value.BurnOdds,
			value.FlameOdds, value.CollisionShape, value.OutlineShape, value.VisualShape, value.UIShape,
			value.LiquidClipShape, value.Solid, value.RequiresCorrectToolForDrops, value.CanContainLiquidSource)
	}
	output.WriteString("}\n\nvar states = [...]State{\n")
	stateOffsets := make([]int, len(blocks))
	for _, value := range states {
		identifier := identifiers[blocks[value.Block].Name]
		fmt.Fprintf(&output, "%sStates[%d],\n", unexportedIdentifier(identifier), stateOffsets[value.Block])
		stateOffsets[value.Block]++
	}
	output.WriteString("}\n\nvar stateHashIndex = [...]uint16{\n")
	for _, value := range hashIndex {
		fmt.Fprintf(&output, "%d,\n", value)
	}
	output.WriteString("}\n")
	const indexName = "block/index_generated.go"
	formatted, err := formattedGo(indexName, generatedSource("block", output.String()))
	if err != nil {
		return nil, 0, err
	}
	files[indexName] = formatted
	return files, len(states), nil
}

type rawBiome struct {
	ID               *int32  `json:"id"`
	Temperature      float32 `json:"temperature"`
	Downfall         float32 `json:"downfall"`
	RedSporeDensity  float32 `json:"redSporeDensity"`
	BlueSporeDensity float32 `json:"blueSporeDensity"`
	AshDensity       float32 `json:"ashDensity"`
	WhiteAshDensity  float32 `json:"whiteAshDensity"`
	FoliageSnow      float32 `json:"foliageSnow"`
	Depth            float32 `json:"depth"`
	Scale            float32 `json:"scale"`
	MapWaterColor    struct {
		A uint8 `json:"a"`
		R uint8 `json:"r"`
		G uint8 `json:"g"`
		B uint8 `json:"b"`
	} `json:"mapWaterColor"`
	Rain bool     `json:"rain"`
	Tags []string `json:"tags"`
}

// generateBiomes emits named biome values and their lookup index.
func generateBiomes(path string, ids map[string]int32, native map[string]rawBiome) (map[string][]byte, int, error) {
	var raw map[string]rawBiome
	if err := readJSON(path, &raw, false); err != nil {
		return nil, 0, err
	}
	if native != nil {
		var err error
		raw, err = applyNativeBiomes(raw, native)
		if err != nil {
			return nil, 0, err
		}
	}
	if len(ids) != len(raw) {
		return nil, 0, fmt.Errorf("biome IDs cover %d names, Cloudburst has %d", len(ids), len(raw))
	}
	names := sortedKeys(raw)
	identifiers, err := exportedIdentifiers(names)
	if err != nil {
		return nil, 0, err
	}
	fileNames, err := generatedFileNames(names)
	if err != nil {
		return nil, 0, err
	}
	files := make(map[string][]byte, len(names)+1)
	seenIDs := make(map[int32]string, len(names))
	for _, name := range names {
		value := raw[name]
		sort.Strings(value.Tags)
		id, hasID := ids[name]
		if !hasID {
			return nil, 0, fmt.Errorf("Cloudburst biome %q has no locked numeric ID", name)
		}
		if id < 0 || id > 65535 {
			return nil, 0, fmt.Errorf("biome %q has invalid numeric ID %d", name, id)
		}
		if previous, exists := seenIDs[id]; exists {
			return nil, 0, fmt.Errorf("biomes %q and %q share numeric ID %d", previous, name, id)
		}
		seenIDs[id] = name
		if value.ID != nil && *value.ID != id {
			return nil, 0, fmt.Errorf("Cloudburst biome %q has ID %d, locked source has %d", name, *value.ID, id)
		}
		color := uint32(value.MapWaterColor.R)<<24 | uint32(value.MapWaterColor.G)<<16 |
			uint32(value.MapWaterColor.B)<<8 | uint32(value.MapWaterColor.A)
		var output bytes.Buffer
		fmt.Fprintf(&output, `// %s is the generated definition for %s.
var %s = Biome{
	Name: %q,
	ID: %d,
	HasID: %t,
	Temperature: %s,
	Downfall: %s,
	Depth: %s,
	Scale: %s,
	RedSporeDensity: %s,
	BlueSporeDensity: %s,
	AshDensity: %s,
	WhiteAshDensity: %s,
	FoliageSnow: %s,
	MapWaterColorRGBA: 0x%08x,
	Rain: %t,
	Tags: %s,
}

`, identifiers[name], name, identifiers[name], name, id, hasID, goFloat(value.Temperature), goFloat(value.Downfall), goFloat(value.Depth),
			goFloat(value.Scale), goFloat(value.RedSporeDensity), goFloat(value.BlueSporeDensity),
			goFloat(value.AshDensity), goFloat(value.WhiteAshDensity), goFloat(value.FoliageSnow),
			color, value.Rain, goStrings(value.Tags))
		fileName := "biome/" + fileNames[name]
		formatted, err := formattedGo(fileName, generatedSource("biome", output.String()))
		if err != nil {
			return nil, 0, err
		}
		files[fileName] = formatted
	}
	var output bytes.Buffer
	output.WriteString("var all = []Biome{\n")
	for _, name := range names {
		fmt.Fprintf(&output, "%s,\n", identifiers[name])
	}
	output.WriteString("}\n")
	const indexName = "biome/index_generated.go"
	formatted, err := formattedGo(indexName, generatedSource("biome", output.String()))
	if err != nil {
		return nil, 0, err
	}
	files[indexName] = formatted
	return files, len(raw), nil
}

