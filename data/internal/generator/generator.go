// GeneratedMarker identifies files owned by the semantic generator.
const GeneratedMarker = "// Code generated by data/cmd/generate; DO NOT EDIT."

// Config identifies the source directories and versions used for generation.
type Config struct {
	CloudburstDir       string
	BDSDir              string
	CloudburstRef       string
	BDSVersion          string
	BiomeIDs            map[string]int32
	NativeBiomes        map[string]rawBiome
	LiquidClipOmissions []LiquidClipOmission
	SourceLockSHA256    string
	NativeBlocks        *nativeblock.Catalog
	NativeRef           string
}

// Stats reports the number of records generated from each source.
type Stats struct {
	BlockStates                 int `json:"block_states"`
	Biomes                      int `json:"biomes"`
	VoxelShapes                 int `json:"voxel_shapes"`
	Entities                    int `json:"entities"`
	Foods                       int `json:"foods"`
	UnavailableLiquidClipShapes int `json:"unavailable_liquid_clip_shapes"`
}

// GenerateCloudburst generates block, biome and named-shape files from the locked extract.
// Keeping this projection separate lets CI verify it without downloading BDS packs.
func GenerateCloudburst(cfg Config) (map[string][]byte, Stats, error) {
	if cfg.CloudburstDir == "" {
		return nil, Stats{}, errors.New("cloudburst directory is required")
	}
	files := make(map[string][]byte)
	var stats Stats

	blockFiles, count, err := generateBlocks(filepath.Join(cfg.CloudburstDir, "blocks.json"), cfg.LiquidClipOmissions, cfg.NativeBlocks)
	if err != nil {
		return nil, stats, fmt.Errorf("generate blocks: %w", err)
	}
	if err := mergeFiles(files, blockFiles); err != nil {
		return nil, stats, err
	}
	stats.BlockStates = count
	stats.UnavailableLiquidClipShapes = len(cfg.LiquidClipOmissions)

	biomeFiles, count, err := generateBiomes(filepath.Join(cfg.CloudburstDir, "stripped_biome_definitions.json"), cfg.BiomeIDs, cfg.NativeBiomes)
	if err != nil {
		return nil, stats, fmt.Errorf("generate biomes: %w", err)
	}
	if err := mergeFiles(files, biomeFiles); err != nil {
		return nil, stats, err
	}
	stats.Biomes = count

	shapeFiles, count, err := generateVoxelShapes(filepath.Join(cfg.CloudburstDir, "voxel_shapes.json"))
	if err != nil {
		return nil, stats, fmt.Errorf("generate voxel shapes: %w", err)
	}
	if err := mergeFiles(files, shapeFiles); err != nil {
		return nil, stats, err
	}
	stats.VoxelShapes = count

	return files, stats, nil
}

// Generate loads the configured sources and returns deterministic catalog-
// relative files. It does not write to disk.
func Generate(cfg Config) (map[string][]byte, Stats, error) {
	if cfg.CloudburstDir == "" || cfg.BDSDir == "" {
		return nil, Stats{}, errors.New("cloudburst and BDS directories are required")
	}
	files, stats, err := GenerateCloudburst(cfg)
	if err != nil {
		return nil, stats, err
	}

	entityFiles, count, err := generateEntities(filepath.Join(
		cfg.BDSDir, "behavior_packs", "vanilla", "entities",
	))
	if err != nil {
		return nil, stats, fmt.Errorf("generate entities: %w", err)
	}
	if err := mergeFiles(files, entityFiles); err != nil {
		return nil, stats, err
	}
	stats.Entities = count

	foodFiles, count, err := generateFoods(filepath.Join(
		cfg.BDSDir, "behavior_packs", "vanilla", "items",
	))
	if err != nil {
		return nil, stats, fmt.Errorf("generate foods: %w", err)
	}
	if err := mergeFiles(files, foodFiles); err != nil {
		return nil, stats, err
	}
	stats.Foods = count

	version, err := formattedGo("version_generated.go", fmt.Sprintf(`%s

package data

const (
	SchemaVersion = 1
	CloudburstRef = %q
	// NativeRef pins native block, biome and item measurements independently of shapes.
	NativeRef = %q
	BDSVersion = %q
	// SemanticSourceLockSHA256 identifies the lock used for semantic generation.
	SemanticSourceLockSHA256 = %q
)

var GeneratedCounts = Counts{
	BlockStates: %d,
	Biomes: %d,
	VoxelShapes: %d,
	Entities: %d,
	Foods: %d,
	UnavailableLiquidClipShapes: %d,
}
`, GeneratedMarker, cfg.CloudburstRef, cfg.NativeRef, cfg.BDSVersion, cfg.SourceLockSHA256, stats.BlockStates, stats.Biomes, stats.VoxelShapes, stats.Entities, stats.Foods, stats.UnavailableLiquidClipShapes))
	if err != nil {
		return nil, stats, err
	}
	files["version_generated.go"] = version

	manifest, err := json.MarshalIndent(struct {
		SchemaVersion       int                  `json:"schema_version"`
		CloudburstRef       string               `json:"cloudburst_ref"`
		NativeRef           string               `json:"native_ref,omitempty"`
		BDSVersion          string               `json:"bds_version"`
		LiquidClipOmissions []LiquidClipOmission `json:"liquid_clip_omissions,omitempty"`
		SourceLockSHA256    string               `json:"source_lock_sha256"`
		Counts              Stats                `json:"counts"`
	}{
		SchemaVersion:       1,
		CloudburstRef:       cfg.CloudburstRef,
		NativeRef:           cfg.NativeRef,
		BDSVersion:          cfg.BDSVersion,
		LiquidClipOmissions: cfg.LiquidClipOmissions,
		SourceLockSHA256:    cfg.SourceLockSHA256,
		Counts:              stats,
	}, "", "  ")
	if err != nil {
		return nil, stats, err
	}
	files["semantic_sources.json"] = append(manifest, '\n')
	return files, stats, nil
}

