// generateFoods emits food properties while skipping non-food item definitions.
func generateFoods(dir string) (map[string][]byte, int, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*.json"))
	if err != nil {
		return nil, 0, err
	}
	if len(paths) == 0 {
		return nil, 0, fmt.Errorf("no item files found in %s", dir)
	}
	values := make([]generatedFood, 0, len(paths))
	for _, path := range paths {
		var raw rawItem
		if err := readJSON(path, &raw, true); err != nil {
			return nil, 0, err
		}
		foodMessage, ok := raw.Item.Components["minecraft:food"]
		if !ok {
			continue
		}
		var food rawFood
		if err := json.Unmarshal(foodMessage, &food); err != nil {
			return nil, 0, fmt.Errorf("%s food: %w", path, err)
		}
		if raw.Item.Description.Identifier == "" {
			return nil, 0, fmt.Errorf("%s has no item identifier", path)
		}
		useDuration, err := rawNumber(raw.Item.Components["minecraft:use_duration"])
		if err != nil {
			return nil, 0, fmt.Errorf("%s use duration: %w", raw.Item.Description.Identifier, err)
		}
		convertsTo, err := rawString(food.UsingConvertsTo)
		if err != nil {
			return nil, 0, fmt.Errorf("%s using_converts_to: %w", raw.Item.Description.Identifier, err)
		}
		values = append(values, generatedFood{
			Name:               raw.Item.Description.Identifier,
			Nutrition:          food.Nutrition,
			SaturationModifier: food.SaturationModifier,
			UseDuration:        useDuration,
			CanAlwaysEat:       food.CanAlwaysEat,
			UsingConvertsTo:    convertsTo,
			Effects:            food.Effects,
		})
	}
	sort.Slice(values, func(i, j int) bool { return values[i].Name < values[j].Name })
	for index := 1; index < len(values); index++ {
		if values[index-1].Name == values[index].Name {
			return nil, 0, fmt.Errorf("duplicate food %s", values[index].Name)
		}
	}
	names := make([]string, len(values))
	for index, value := range values {
		names[index] = value.Name
	}
	identifiers, err := exportedIdentifiers(names)
	if err != nil {
		return nil, 0, err
	}
	fileNames, err := generatedFileNames(names)
	if err != nil {
		return nil, 0, err
	}

	files := make(map[string][]byte, len(values)+1)
	for _, value := range values {
		var output bytes.Buffer
		fmt.Fprintf(&output, `// %s is the generated definition for %s.
var %s = Food{
	Name: %q,
	Nutrition: %d,
	SaturationModifier: %q,
	UseDuration: %s,
	CanAlwaysEat: %t,
	UsingConvertsTo: %q,
	Effects: []Effect{
`, identifiers[value.Name], value.Name, identifiers[value.Name], value.Name, value.Nutrition, value.SaturationModifier, goFloat(value.UseDuration),
			value.CanAlwaysEat, value.UsingConvertsTo)
		for _, effect := range value.Effects {
			fmt.Fprintf(&output, "{Name: %q, Chance: %s, Duration: %s, Amplifier: %d},\n",
				effect.Name, goFloat(effect.Chance), goFloat(effect.Duration), effect.Amplifier)
		}
		output.WriteString("},\n}\n")
		fileName := "item/" + fileNames[value.Name]
		formatted, err := formattedGo(fileName, generatedSource("item", output.String()))
		if err != nil {
			return nil, 0, err
		}
		files[fileName] = formatted
	}
	var output bytes.Buffer
	output.WriteString("var all = []Food{\n")
	for _, value := range values {
		fmt.Fprintf(&output, "%s,\n", identifiers[value.Name])
	}
	output.WriteString("}\n")
	const indexName = "item/index_generated.go"
	formatted, err := formattedGo(indexName, generatedSource("item", output.String()))
	if err != nil {
		return nil, 0, err
	}
	files[indexName] = formatted
	return files, len(values), nil
}

// componentNumber reads an optional scalar or range from a component field.
func componentNumber(components map[string]json.RawMessage, componentName, fieldName string) (optionalNumber, error) {
	message, ok := components[componentName]
	if !ok {
		return optionalNumber{}, nil
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(message, &fields); err != nil {
		return optionalNumber{}, err
	}
	value, ok := fields[fieldName]
	if !ok {
		return optionalNumber{}, nil
	}
	return rawNumberOrRange(value)
}

// rawNumberOrRange decodes an optional fixed value or random range.
// rawNumber decodes a scalar, treating an absent field as zero.
func rawNumberOrRange(message json.RawMessage) (optionalNumber, error) {
	if len(message) == 0 || bytes.Equal(bytes.TrimSpace(message), []byte("null")) {
		return optionalNumber{}, nil
	}
	var scalar float32
	if err := json.Unmarshal(message, &scalar); err == nil {
		return optionalNumber{Value: scalar, Present: true}, nil
	}
	var ranged struct {
		Min float32 `json:"range_min"`
		Max float32 `json:"range_max"`
	}
	if err := json.Unmarshal(message, &ranged); err != nil {
		return optionalNumber{}, err
	}
	return optionalNumber{Min: ranged.Min, Max: ranged.Max, Ranged: true, Present: true}, nil
}

func rawNumber(message json.RawMessage) (float32, error) {
	if len(message) == 0 || bytes.Equal(bytes.TrimSpace(message), []byte("null")) {
		return 0, nil
	}
	var value float32
	if err := json.Unmarshal(message, &value); err != nil {
		return 0, err
	}
	return value, nil
}

// rawString accepts either a string or a named string component.
func rawString(message json.RawMessage) (string, error) {
	if len(message) == 0 || bytes.Equal(bytes.TrimSpace(message), []byte("null")) {
		return "", nil
	}
	var value string
	if err := json.Unmarshal(message, &value); err == nil {
		return value, nil
	}
	var object struct {
		Value string `json:"value"`
		Name  string `json:"name"`
	}
	if err := json.Unmarshal(message, &object); err != nil {
		return "", err
	}
	if object.Value != "" {
		return object.Value, nil
	}
	return object.Name, nil
}

// decodeShape distinguishes unavailable shapes from available empty shapes.
func decodeShape(message json.RawMessage) ([]generatedBox, bool, error) {
	trimmed := bytes.TrimSpace(message)
	if len(trimmed) == 0 || bytes.Equal(trimmed, []byte("null")) {
		return nil, false, nil
	}
	var value any
	decoder := json.NewDecoder(bytes.NewReader(trimmed))
	decoder.UseNumber()
	if err := decoder.Decode(&value); err != nil {
		return nil, false, err
	}
	array, ok := value.([]any)
	if !ok {
		return nil, false, fmt.Errorf("expected array, got %T", value)
	}
	if len(array) == 0 {
		return []generatedBox{}, true, nil
	}
	if len(array) == 6 {
		if box, ok := anyBox(array); ok {
			if err := validateBox(box); err != nil {
				return nil, false, err
			}
			return []generatedBox{box}, true, nil
		}
	}
	boxes := make([]generatedBox, 0, len(array))
	for _, entry := range array {
		values, ok := entry.([]any)
		if !ok {
			return nil, false, fmt.Errorf("expected box array, got %T", entry)
		}
		box, ok := anyBox(values)
		if !ok {
			return nil, false, fmt.Errorf("expected six numeric box coordinates")
		}
		if err := validateBox(box); err != nil {
			return nil, false, err
		}
		boxes = append(boxes, box)
	}
	return boxes, true, nil
}

// anyBox decodes six numeric coordinates into a block-local box.
func anyBox(values []any) (generatedBox, bool) {
	if len(values) != 6 {
		return generatedBox{}, false
	}
	var box generatedBox
	for index, value := range values {
		number, ok := value.(json.Number)
		if !ok {
			return generatedBox{}, false
		}
		parsed, err := strconv.ParseFloat(string(number), 32)
		if err != nil {
			return generatedBox{}, false
		}
		box[index] = float32(parsed)
	}
	return box, true
}

// validateBox rejects non-finite coordinates and reversed bounds.
func validateBox(box generatedBox) error {
	for _, value := range box {
		if math.IsNaN(float64(value)) || math.IsInf(float64(value), 0) {
			return errors.New("box contains a non-finite coordinate")
		}
	}
	if box[0] > box[3] || box[1] > box[4] || box[2] > box[5] {
		return fmt.Errorf("box minimum exceeds maximum: %v", box)
	}
	return nil
}

// shapeKey identifies a box sequence without rounding its coordinates.
func shapeKey(boxes []generatedBox) string {
	var output strings.Builder
	for _, box := range boxes {
		for _, value := range box {
			fmt.Fprintf(&output, "%08x", math.Float32bits(value))
		}
	}
	return output.String()
}

// parseRGBA decodes a hexadecimal RGBA color, or zero when absent.
func parseRGBA(value string) (uint32, error) {
	if value == "" {
		return 0, nil
	}
	if len(value) != 9 || value[0] != '#' {
		return 0, fmt.Errorf("expected #RRGGBBAA, got %q", value)
	}
	parsed, err := strconv.ParseUint(value[1:], 16, 32)
	return uint32(parsed), err
}

// readJSON loads a source document and optionally removes JSON comments.
func readJSON(path string, destination any, allowComments bool) error {
	content, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	content = bytes.TrimPrefix(content, []byte{0xef, 0xbb, 0xbf})
	if allowComments {
		content, err = stripJSONComments(content)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
	}
	if err := json.Unmarshal(content, destination); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

// stripJSONComments removes comments without changing quoted strings.
func stripJSONComments(input []byte) ([]byte, error) {
	output := make([]byte, 0, len(input))
	inString, escaped := false, false
	for index := 0; index < len(input); {
		current := input[index]
		if inString {
			output = append(output, current)
			index++
			if escaped {
				escaped = false
				continue
			}
			if current == '\\' {
				escaped = true
			} else if current == '"' {
				inString = false
			}
			continue
		}
		if current == '"' {
			inString = true
			output = append(output, current)
			index++
			continue
		}
		if current != '/' || index+1 == len(input) {
			output = append(output, current)
			index++
			continue
		}
		next := input[index+1]
		switch next {
		case '/':
			output = append(output, ' ', ' ')
			index += 2
			for index < len(input) && input[index] != '\n' {
				output = append(output, ' ')
				index++
			}
		case '*':
			output = append(output, ' ', ' ')
			index += 2
			closed := false
			for index < len(input) {
				if index+1 < len(input) && input[index] == '*' && input[index+1] == '/' {
					output = append(output, ' ', ' ')
					index += 2
					closed = true
					break
				}
				if input[index] == '\n' {
					output = append(output, '\n')
				} else {
					output = append(output, ' ')
				}
				index++
			}
			if !closed {
				return nil, errors.New("unterminated block comment")
			}
		default:
			output = append(output, current)
			index++
		}
	}
	if inString {
		return nil, errors.New("unterminated string")
	}
	return output, nil
}

// Write replaces generated files as one rollback-protected batch, then removes
// stale files bearing marker in the output packages. Handwritten files
// and files owned by other generators are never removed.
func Write(outputDir, marker string, files map[string][]byte) error {
	return writeWithRename(outputDir, marker, files, os.Rename)
}

// writeWithRename stages a batch and restores replaced files if installation fails.
func writeWithRename(outputDir, marker string, files map[string][]byte, rename func(string, string) error) error {
	expected := make(map[string]struct{}, len(files))
	names := make([]string, 0, len(files))
	for name := range files {
		clean := filepath.Clean(filepath.FromSlash(name))
		if filepath.IsAbs(clean) || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
			return fmt.Errorf("generated path escapes output directory: %q", name)
		}
		expected[filepath.Join(outputDir, clean)] = struct{}{}
		names = append(names, name)
	}

	sort.Strings(names)
	type stagedFile struct {
		temporary string
		final     string
	}
	staged := make([]stagedFile, 0, len(names))
	cleanupStaged := func() {
		for _, file := range staged {
			_ = os.Remove(file.temporary)
		}
	}
	for _, name := range names {
		path := filepath.Join(outputDir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			cleanupStaged()
			return err
		}
		temporary, err := os.CreateTemp(filepath.Dir(path), ".generate-*")
		if err != nil {
			cleanupStaged()
			return err
		}
		temporaryPath := temporary.Name()
		if _, err = temporary.Write(files[name]); err == nil {
			err = temporary.Chmod(0o644)
		}
		if closeErr := temporary.Close(); err == nil {
			err = closeErr
		}
		if err != nil {
			_ = os.Remove(temporaryPath)
			cleanupStaged()
			return err
		}
		staged = append(staged, stagedFile{temporary: temporaryPath, final: path})
	}
	type committedFile struct {
		final  string
		backup string
	}
	committed := make([]committedFile, 0, len(staged))
	rollback := func() error {
		var rollbackErrors []error
		for index := len(committed) - 1; index >= 0; index-- {
			file := committed[index]
			if err := os.Remove(file.final); err != nil && !os.IsNotExist(err) {
				rollbackErrors = append(rollbackErrors, fmt.Errorf("remove replacement %s: %w", file.final, err))
				continue
			}
			if file.backup != "" {
				if err := rename(file.backup, file.final); err != nil {
					rollbackErrors = append(rollbackErrors, fmt.Errorf("restore %s: %w", file.final, err))
				}
			}
		}
		return errors.Join(rollbackErrors...)
	}
	for index, file := range staged {
		backup := ""
		info, err := os.Lstat(file.final)
		if err == nil {
			if !info.Mode().IsRegular() {
				for _, remaining := range staged[index:] {
					_ = os.Remove(remaining.temporary)
				}
				return errors.Join(
					fmt.Errorf("generated target is not a regular file: %s", file.final),
					rollback(),
				)
			}
			backupFile, createErr := os.CreateTemp(filepath.Dir(file.final), ".generate-backup-*")
			if createErr != nil {
				for _, remaining := range staged[index:] {
					_ = os.Remove(remaining.temporary)
				}
				return errors.Join(createErr, rollback())
			}
			backup = backupFile.Name()
			if closeErr := backupFile.Close(); closeErr != nil {
				_ = os.Remove(backup)
				for _, remaining := range staged[index:] {
					_ = os.Remove(remaining.temporary)
				}
				return errors.Join(closeErr, rollback())
			}
			if removeErr := os.Remove(backup); removeErr != nil {
				for _, remaining := range staged[index:] {
					_ = os.Remove(remaining.temporary)
				}
				return errors.Join(removeErr, rollback())
			}
			if err = rename(file.final, backup); err != nil {
				for _, remaining := range staged[index:] {
					_ = os.Remove(remaining.temporary)
				}
				return errors.Join(err, rollback())
			}
		} else if !os.IsNotExist(err) {
			for _, remaining := range staged[index:] {
				_ = os.Remove(remaining.temporary)
			}
			return errors.Join(err, rollback())
		}
		committed = append(committed, committedFile{final: file.final, backup: backup})
		if err = rename(file.temporary, file.final); err != nil {
			for _, remaining := range staged[index:] {
				_ = os.Remove(remaining.temporary)
			}
			return errors.Join(err, rollback())
		}
	}
	for _, file := range committed {
		if file.backup != "" {
			_ = os.Remove(file.backup)
		}
	}

	// Derive package directories from this run's outputs, then remove only files
	// bearing this generator's marker. Other generators may share a package.
	directories := make(map[string]struct{})
	for _, name := range names {
		directories[filepath.Dir(filepath.Join(outputDir, filepath.FromSlash(name)))] = struct{}{}
	}
	for _, dir := range sortedKeys(directories) {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return err
		}
		for _, entry := range entries {
			if !entry.Type().IsRegular() || !strings.HasSuffix(entry.Name(), "_generated.go") {
				continue
			}
			path := filepath.Join(dir, entry.Name())
			if _, ok := expected[path]; ok {
				continue
			}
			content, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !bytes.HasPrefix(content, []byte(marker+"\n")) {
				continue
			}
			if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
				return fmt.Errorf("remove stale generated file %s: %w", path, err)
			}
		}
	}
	return nil
}

// mergeFiles combines output sets and rejects duplicate paths.
func mergeFiles(destination, source map[string][]byte) error {
	for name, content := range source {
		if _, exists := destination[name]; exists {
			return fmt.Errorf("duplicate generated path %s", name)
		}
		destination[name] = content
	}
	return nil
}

// generatedSource wraps declarations with this generator's ownership marker.
func generatedSource(packageName, body string) string {
	return GeneratedMarker + "\n\npackage " + packageName + "\n\n" + body
}

// exportedIdentifiers derives valid, unique Go names from source identifiers.
func exportedIdentifiers(names []string) (map[string]string, error) {
	identifiers := make(map[string]string, len(names))
	seen := make(map[string]string, len(names))
	for _, name := range names {
		local := localName(name)
		parts := strings.FieldsFunc(local, func(value rune) bool {
			return !unicode.IsLetter(value) && !unicode.IsDigit(value)
		})
		var identifier strings.Builder
		for _, part := range parts {
			runes := []rune(part)
			if len(runes) == 0 {
				continue
			}
			identifier.WriteRune(unicode.ToUpper(runes[0]))
			identifier.WriteString(string(runes[1:]))
		}
		value := identifier.String()
		if value == "" {
			return nil, fmt.Errorf("cannot derive Go identifier from %q", name)
		}
		if first := []rune(value)[0]; unicode.IsDigit(first) {
			value = "X" + value
		}
		if previous, ok := seen[value]; ok {
			return nil, fmt.Errorf("Go identifier %s collides for %q and %q", value, previous, name)
		}
		seen[value] = name
		identifiers[name] = value
	}
	return identifiers, nil
}

// generatedFileNames derives unique output filenames from source identifiers.
func generatedFileNames(names []string) (map[string]string, error) {
	fileNames := make(map[string]string, len(names))
	seen := make(map[string]string, len(names))
	for _, name := range names {
		var base strings.Builder
		var previousLetterOrDigit bool
		for _, value := range localName(name) {
			if !unicode.IsLetter(value) && !unicode.IsDigit(value) {
				if base.Len() != 0 && !strings.HasSuffix(base.String(), "_") {
					base.WriteByte('_')
				}
				previousLetterOrDigit = false
				continue
			}
			if unicode.IsUpper(value) && previousLetterOrDigit {
				base.WriteByte('_')
			}
			base.WriteRune(unicode.ToLower(value))
			previousLetterOrDigit = true
		}
		value := strings.Trim(base.String(), "_") + "_generated.go"
		if value == "_generated.go" {
			return nil, fmt.Errorf("cannot derive generated filename from %q", name)
		}
		if previous, ok := seen[value]; ok {
			return nil, fmt.Errorf("generated filename %s collides for %q and %q", value, previous, name)
		}
		seen[value] = name
		fileNames[name] = value
	}
	return fileNames, nil
}

// localName removes the namespace from a source identifier.
func localName(name string) string {
	if index := strings.LastIndexByte(name, ':'); index >= 0 {
		return name[index+1:]
	}
	return name
}

// unexportedIdentifier lowers the first letter of a generated Go name.
func unexportedIdentifier(identifier string) string {
	runes := []rune(identifier)
	runes[0] = unicode.ToLower(runes[0])
	return string(runes)
}

// formattedGo formats an emitted source file and labels syntax errors.
func formattedGo(name, source string) ([]byte, error) {
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return nil, fmt.Errorf("format %s: %w", name, err)
	}
	return formatted, nil
}

// goFloat renders a float32 without losing its represented value.
func goFloat(value float32) string {
	return strconv.FormatFloat(float64(value), 'g', -1, 32)
}

// goStrings renders a string slice as a Go expression.
func goStrings(values []string) string {
	if len(values) == 0 {
		return "nil"
	}
	var output strings.Builder
	output.WriteString("[]string{")
	for _, value := range values {
		fmt.Fprintf(&output, "%q,", value)
	}
	output.WriteByte('}')
	return output.String()
}

// sortedKeys returns map keys in lexical order for deterministic output.
func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
