// Package mininggen joins native tool requirements with retained special-tool evidence.
package mininggen

import "strings"

// GeneratedMarker identifies files owned by the mining generator.
const GeneratedMarker = "// Code generated by data/cmd/mininggen; DO NOT EDIT."

const (
	pickaxe = 1 << iota
	axe
	shovel
	hoe
	sword
	shears
)

// toolExpression renders a family set with named constants for reviewable output.
func toolExpression(families uint8) string {
	var names []string
	for _, tool := range []struct {
		mask uint8
		name string
	}{
		{pickaxe, "ToolPickaxe"}, {axe, "ToolAxe"}, {shovel, "ToolShovel"},
		{hoe, "ToolHoe"}, {sword, "ToolSword"}, {shears, "ToolShears"},
	} {
		if families&tool.mask != 0 {
			names = append(names, tool.name)
		}
	}
	if len(names) == 0 {
		return "0"
	}
	return strings.Join(names, " | ")
}
